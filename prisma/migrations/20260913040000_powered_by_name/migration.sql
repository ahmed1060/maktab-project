-- The name shown in the "Powered by" mark, previously a string literal inside
-- DashboardShell.
--
-- A column rather than a constant so the attribution can change without a
-- deploy — a rebrand, or a reseller putting their own name on it. Defaults to
-- SHSD, which is exactly what the component rendered before, so this migration
-- changes nothing visible.
--
-- Separate from show_powered_by rather than folded into it: that migration is
-- already applied and checksummed, and rewriting an applied migration is how a
-- migration history stops matching the database it describes.
ALTER TABLE "SystemSettings" ADD COLUMN "poweredByName" TEXT NOT NULL DEFAULT 'SHSD';
